def get_dmon_matchup(hero):

    danger = D_MON_DANGER.get(hero, 6)

    if danger >= 8:
        reason = (
            "D.Monはジェット・ドライブで距離を詰めながら、"
            "パワー・バリアと近距離攻撃で強く圧力をかけられるため、"
            "安全な位置を維持しにくい相手です。"
        )

        advice = (
            "D.Monと正面で長く戦わず、遮蔽物と味方を利用しましょう。"
            "接近された後ではなく、接近してくる前に位置を変えることを意識しましょう。"
        )

    elif danger >= 7:
        reason = (
            "D.Monの機動力と前方防御によって、"
            "得意な距離や射線を維持しにくくなる場合があります。"
        )

        advice = (
            "パワー・バリアに攻撃を集中し続けず、"
            "横方向からの攻撃や距離の取り直しを意識しましょう。"
        )

    else:
        reason = (
            "D.Monは近距離で圧力をかけられるタンクですが、"
            "位置取りや機動力を活かせば対応できる場面があります。"
        )

        advice = (
            "正面から長く戦うことを避け、"
            "D.Monの位置とバリアの使用状況を確認しながら戦いましょう。"
        )

    return {
        "danger": danger,
        "reason": reason,
        "advice": advice
    }